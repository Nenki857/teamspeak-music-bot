import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdirSync, mkdtempSync } from 'node:fs';
import { resolve } from 'node:path';
import { randomBytes } from 'node:crypto';
mkdirSync(resolve('work/server-library-tests'), { recursive: true });
process.env.TSMD_DATA_DIR = mkdtempSync(resolve('work/server-library-tests/run-'));
const [{ Store }, { createVault }, { requireCore }, { exportLibrary, importLibrary }] = await Promise.all([import('../src/worker/store.mjs'), import('../src/shared/security.mjs'), import('../src/worker/paths.mjs'), import('../src/server/library-migration.mjs')]);
test('batch playlist migration preserves identifiers, descriptions and attribution without copying credentials or overwriting edits', t => {
  const source = new Store(createVault(randomBytes(32))); t.after(() => source.close());
  source.set('neteaseCookie', 'private-cookie-must-never-export');
  source.save({ name: 'Private server', serverAddress: '127.0.0.1', serverPassword: 'private-server-password' });
  const local = source.saveLocalPlaylist({ name: 'Friends', description: '共同整理的简介', openedBy: 'Alice', songs: [{ id: '12', name: 'Song 12', artist: 'Artist' }, { id: '11', name: 'Song 11', artist: 'Artist' }] });
  source.publishPlaylist({ id: '900', name: 'Public reference', songCount: 10 }, 'Bob');
  const exported = exportLibrary(resolve(process.env.TSMD_DATA_DIR, 'app.db'));
  assert.equal(JSON.stringify(exported).includes('private-'), false);
  const Database = requireCore('better-sqlite3'); const target = Object.create(Store.prototype); target.db = new Database(':memory:');
  for (const row of source.db.prepare("SELECT sql FROM sqlite_master WHERE type='table' AND name IN ('local_playlists','open_playlists')").all()) target.db.exec(row.sql);
  t.after(() => target.close());
  assert.deepEqual(importLibrary(target, exported), { added: 2, skipped: 0 });
  const imported = target.localPlaylist(local.id);
  assert.equal(imported.description, local.description); assert.equal(imported.openedBy, 'Alice');
  assert.deepEqual(imported.songs.map(song => song.id), ['12', '11']); assert.equal(target.openPlaylists()[0].openedBy, 'Bob');
  target.updateLocalPlaylist({ id: imported.id, name: 'Changed after migration', songs: imported.songs, expectedUpdatedAt: imported.updatedAt });
  assert.deepEqual(importLibrary(target, exported), { added: 0, skipped: 2 });
  assert.equal(target.localPlaylist(local.id).name, 'Changed after migration');
  assert.throws(() => importLibrary(target, { ...exported, localPlaylists: [{ ...exported.localPlaylists[0], id: 'invalid' }] }), /ID 无效/);
  assert.equal(target.localPlaylists().length, 1);
});
