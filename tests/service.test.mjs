import test from 'node:test';
import assert from 'node:assert/strict';
import { randomBytes, randomUUID } from 'node:crypto';
import { resolve } from 'node:path';
import { mkdirSync, readFileSync } from 'node:fs';
process.env.TSMD_DATA_DIR = resolve('work/test-' + randomUUID());
mkdirSync(process.env.TSMD_DATA_DIR, { recursive: true });
const { createVault } = await import('../src/shared/security.mjs');
const { Service } = await import('../src/worker/service.mjs');
const { createShareServer } = await import('../src/worker/share-server.mjs');
test('real core loads; presets persist encrypted; HTTP cannot reach owner controls; run revokes sessions', async t => {
  const service = new Service(createVault(randomBytes(32)), () => {}); await service.init();
  const server = await createShareServer(service); t.after(() => { server.close(); service.close(); });
  assert.equal(service.snapshot().ready, true); assert.equal(service.snapshot().phase, 'stopped');
  const preset = await service.rpc('presets.save', { name: '测试', serverAddress: 'ts.example.com:9999', nickname: '音乐', channelId: '15', serverPassword: 'secret-a', channelPassword: 'secret-b' });
  assert.equal(preset.serverPort, 9999); assert.equal(preset.hasServerPassword, true); assert.equal(preset.serverPassword, undefined);
  assert.equal(service.store.read(preset.id).serverPassword, 'secret-a');
  assert.ok(!readFileSync(resolve(process.env.TSMD_DATA_DIR, 'app.db')).includes(Buffer.from('secret-a')));
  assert.ok(!JSON.stringify(service.snapshot()).includes('secret-a'));
  await assert.rejects(service.rpc('presets.save', { name: 'bad', serverAddress: 'https://example.com' }));
  // Network access restrictions are independent of the actual TS connection.
  service.authority.beginRun(); const grant = service.authority.create('朋友', ['view', 'skip']);
  const origin = `http://127.0.0.1:${server.port}`;
  const page = await fetch(origin + '/'); const csp = page.headers.get('content-security-policy');
  assert.match(csp, /img-src 'self' data: https:\/\/music\.126\.net https:\/\/\*\.music\.126\.net;/);
  assert.match(csp, /script-src 'self';/); assert.ok(!csp.includes('img-src *'));
  const post = async (path, input, extras = {}) => { const response = await fetch(origin + path, { method: 'POST', headers: { Origin: origin, 'Content-Type': 'application/json', ...extras }, body: JSON.stringify(input) }); return { response, data: await response.json() }; };
  const exchange = await post('/api/share/exchange', { token: grant.raw }); assert.equal(exchange.data.ok, true);
  const cookie = exchange.response.headers.get('set-cookie').split(';')[0]; const credentials = { Cookie: cookie, 'X-TSMD-CSRF': exchange.data.csrf };
  const status = await post('/api/share/rpc', { method: 'status', id: randomUUID() }, credentials);
  assert.equal(status.data.ok, true); assert.equal(status.data.result.presets, undefined); assert.equal(status.data.result.auth, undefined);
  assert.equal(status.data.result.audioHealth, undefined, 'audio diagnostics stay on the owner desktop');
  assert.equal(service.snapshot().audioHealth.tsConnectionStatistics, 'unsupported');
  const denied = await post('/api/share/rpc', { method: 'auth.qr', id: randomUUID() }, credentials); assert.equal(denied.data.ok, false);
  const noCsrf = await post('/api/share/rpc', { method: 'status', id: randomUUID() }, { Cookie: cookie }); assert.equal(noCsrf.data.ok, false);
  const wrongOrigin = await post('/api/share/exchange', { token: grant.raw }, { Origin: 'https://attacker.example' }); assert.equal(wrongOrigin.data.ok, false);
  service.authority.endRun(); const revoked = await post('/api/share/rpc', { method: 'status', id: randomUUID() }, credentials); assert.equal(revoked.data.ok, false);
  const blockedPath = await fetch(origin + '/api/player'); assert.equal(blockedPath.status, 404);
});
